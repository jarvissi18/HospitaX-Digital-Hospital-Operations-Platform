// =====================================================
// STAFF / USER TYPE
// =====================================================

export type StaffRole =
  | "Administrator"
  | "Doctor"
  | "Nurse"
  | "Receptionist"
  | "Housekeeper";

export interface User {
  // ---------------------------------------------------
  // DATABASE
  // ---------------------------------------------------

  id: number;

  // ---------------------------------------------------
  // IDENTITY
  // ---------------------------------------------------

  full_name: string;

  // ---------------------------------------------------
  // CONTACT
  // ---------------------------------------------------

  email?: string | null;

  mobile?: string | null;

  // ---------------------------------------------------
  // STAFF IDENTITY
  // ---------------------------------------------------

  // Generated automatically by the backend.
  employee_id?: string | null;

  // ---------------------------------------------------
  // ROLE
  // ---------------------------------------------------

  role: StaffRole | string;

  // ---------------------------------------------------
  // WORK DETAILS
  // ---------------------------------------------------

  shift?: string | null;

  // ---------------------------------------------------
  // ACCOUNT STATUS
  // ---------------------------------------------------

  is_active: string;
}